const dictionaries = { en, es };

export const monthLabels = {
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
  es: ["Ene", "Feb", "Mar", "Abr", "May", "Jun", "Jul", "Ago", "Sep", "Oct", "Nov", "Dic"]
};

export function useT(): (key: Key) => string {
  const lang = useStore((s) => s.lang);
  return (key) => dictionaries[lang][key] ?? key;
}

export function useMonths(): string[] {
  const lang = useStore((s) => s.lang);
  return monthLabels[lang];
}

export function cropLabel(t: (k: Key) => string, crop: string | null): string {
  if (!crop) return t("twin.bare");
  const key = `crop.${crop}` as Key;
  const label = t(key);
  return label === key ? crop : label;
}
